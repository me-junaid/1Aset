export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return MOCK_BLOG_POSTS.find((post) => post.slug === slug);
}

export function getRelatedPosts(currentSlug: string, limit = 3): BlogPost[] {
  const current = getBlogPostBySlug(currentSlug);
  if (!current) return MOCK_BLOG_POSTS.slice(0, limit);

  const related = MOCK_BLOG_POSTS.filter(
    (post) => post.slug !== currentSlug && post.category === current.category
  );

  if (related.length < limit) {
    const additional = MOCK_BLOG_POSTS.filter(
      (post) => post.slug !== currentSlug && post.category !== current.category
    );
    return [...related, ...additional].slice(0, limit);
  }

  return related.slice(0, limit);
}
